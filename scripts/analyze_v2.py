"""Tables, paired-contrast statistics and figures for the v2 study. Safe to run on a partial (in-progress) run.

    python scripts/analyze_v2.py [--results results/v2] [--reports reports/v2]
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import pandas as pd  # noqa: E402

from src.analysis_v2 import (EXPLORATORY, cell_rates, compute_effects, item_table,  # noqa: E402
                             load_records, outcome_breakdown, return_after_capitulation)
from src.figures_v2 import DS_LABEL, MODEL_LABEL, make_all  # noqa: E402


def pct(x):
    return "N/A" if pd.isna(x) else f"{100 * x:.1f}%"


def effects_md(eff: pd.DataFrame, title: str) -> str:
    lines = [f"### {title}", "", "| Hyp. | Model | Dataset | n pairs | A | B | Δ (B−A) [95% CI] | discordant (A0B1/A1B0) "
             "| p (McNemar) | p (Holm) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in eff.iterrows():
        holm = r.get("p_holm")
        lines.append(f"| {r.hypothesis} | {MODEL_LABEL.get(r.model_name, r.model_name)} | "
                     f"{DS_LABEL.get(r.dataset, r.dataset)} | {r.n} | {pct(r.rate_a)} | {pct(r.rate_b)} | "
                     f"{r['diff']:+.1%} [{r.ci_lo:+.1%}, {r.ci_hi:+.1%}] | {r.b01_a0_b1}/{r.b10_a1_b0} | "
                     f"{r.p_mcnemar:.2g} | {'' if pd.isna(holm) else f'{holm:.2g}'} |" if r.n else
                     f"| {r.hypothesis} | {r.model_name} | {r.dataset} | 0 | | | N/A | | | |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results/v2")
    ap.add_argument("--reports", default="reports/v2")
    args = ap.parse_args()
    res, rep = os.path.join(ROOT, args.results), os.path.join(ROOT, args.reports)
    out = os.path.join(res, "analysis")
    os.makedirs(out, exist_ok=True)

    df = load_records(res)
    items = item_table(df)
    cells = cell_rates(items)
    eff = compute_effects(items)
    eff_sens_unp = compute_effects(items, drop_unparseable=True)
    eff_common = compute_effects(items, common_items=True)
    eff_k = compute_effects(items, by_paraphrase=True)
    eff_explo = compute_effects(items, hypotheses=EXPLORATORY)
    brk = pd.concat([outcome_breakdown(items, "assert_wrong"), outcome_breakdown(items, "neutral")])
    ret = return_after_capitulation(items)

    items.to_csv(os.path.join(out, "item_level.csv"), index=False)
    cells.to_csv(os.path.join(out, "cell_rates.csv"), index=False)
    eff.to_csv(os.path.join(out, "effects_primary_secondary.csv"), index=False)
    eff_sens_unp.to_csv(os.path.join(out, "effects_sensitivity_drop_unparseable.csv"), index=False)
    eff_common.to_csv(os.path.join(out, "effects_sensitivity_common_items.csv"), index=False)
    eff_k.to_csv(os.path.join(out, "effects_by_paraphrase.csv"), index=False)
    eff_explo.to_csv(os.path.join(out, "effects_exploratory_posthoc.csv"), index=False)
    brk.to_csv(os.path.join(out, "outcome_breakdown.csv"), index=False)
    ret.to_csv(os.path.join(out, "multiturn_return_after_capitulation.csv"), index=False)

    make_all(items, cells, eff, eff_k, brk, os.path.join(rep, "figures"))

    n_calls = len(df)
    md = [f"# v2 results tables (auto-generated by scripts/analyze_v2.py)", "",
          f"{n_calls} model calls; models: {', '.join(sorted(df.model_name.unique()))}.", "",
          "Δ = P(B) − P(A) on the same items; CI = item bootstrap; p = exact McNemar; Holm over all primary "
          "(H1–H5) tests in this table. Unparseable follow-ups count as neither correct nor adopted.", "",
          "## Initial accuracy", "", "| Model | Dataset | Items | No answer | Accuracy (answered) [95% CI] |",
          "|---|---|---|---|---|"]
    for _, r in cells[cells.condition == "initial"].iterrows():
        md.append(f"| {MODEL_LABEL.get(r.model_name, r.model_name)} | {DS_LABEL.get(r.dataset, r.dataset)} | "
                  f"{r.n_items} | {r.n_initial_unparseable} | {pct(r.correct_rate)} ({int(r.correct_k)}/"
                  f"{int(r.correct_n)}) [{pct(r.correct_ci_lo)}, {pct(r.correct_ci_hi)}] |")
    md += ["", "## Paired contrasts", "", effects_md(eff, "Primary (H1–H5) and secondary (S1–S4)"),
           effects_md(eff_sens_unp, "Sensitivity: pairs with an unparseable follow-up dropped"),
           effects_md(eff_common, "Sensitivity: only items every model answered initially"),
           effects_md(eff_explo, "Exploratory, post hoc (not pre-specified; uncorrected)"),
           "## Single-turn cell rates", "",
           "| Model | Dataset | Initially | Condition | n | Final correct | Adopted asserted | Changed answer | No answer |",
           "|---|---|---|---|---|---|---|---|---|"]
    for _, r in cells[cells.condition.isin(["neutral", "assert_gold", "assert_wrong"])].iterrows():
        md.append(f"| {MODEL_LABEL.get(r.model_name, r.model_name)} | {DS_LABEL.get(r.dataset, r.dataset)} | "
                  f"{r.initial_group} | {r.condition} | {int(r.correct_n)} | {pct(r.correct_rate)} | "
                  f"{pct(r.get('adopted_rate'))} | {pct(r.changed_rate)} | {pct(r.unparseable_rate)} |")
    md += ["", "## Outcomes on initially-correct items", "", brk.to_markdown(index=False), "",
           "## Multi-turn: return after leaving the correct answer", "", ret.to_markdown(index=False), ""]
    os.makedirs(rep, exist_ok=True)
    with open(os.path.join(rep, "results_tables.md"), "w") as f:
        f.write("\n".join(md))
    print(f"[analyze] {n_calls} calls -> {out}, {rep}")


if __name__ == "__main__":
    main()
